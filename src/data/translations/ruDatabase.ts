/**
 * Looks up full operator localization
 */
export function getOperatorLocalizationRu(charId: string): RuOperatorLocalization | undefined {
  if (RU_OPERATORS_DB[charId]) {
    return RU_OPERATORS_DB[charId];
  }
  const aliased = OPERATOR_ID_ALIASES[charId];
  if (aliased && RU_OPERATORS_DB[aliased]) {
    return RU_OPERATORS_DB[aliased];
  }
  const cnComp = CN_OPERATORS_LOCALIZATION[charId] || (aliased ? CN_OPERATORS_LOCALIZATION[aliased] : undefined);
  if (cnComp) {
    return {
      nameRu: cnComp.nameRu,
      quote: cnComp.quoteRu,
      trait: cnComp.traitRu,
      talents: cnComp.talents.map((t) => ({
        name: t.nameRu,
        description: t.descriptionRu,
      })),
    };
  }
  return undefined;
}

/**
 * Looks up skill localization
 */
export function getSkillLocalizationRu(
  charId: string,
  skillId: string,
  rawName: string
): RuSkillLocalization | undefined {
  const op = RU_OPERATORS_DB[charId];
  if (op?.skills?.[skillId]) {
    return op.skills[skillId];
  }
  return RU_GENERIC_SKILLS[rawName];
}

/**
 * Looks up skin localization
 */
export function getSkinLocalizationRu(
  charId: string,
  skinId: string,
  rawGroupName?: string
): RuSkinLocalization | undefined {
  const op = RU_OPERATORS_DB[charId];
  const skin = op?.skins?.[skinId];
  const translatedGroup = rawGroupName ? RU_SKIN_BRANDS[rawGroupName] : undefined;

  if (skin) {
    return {
      ...skin,
      skinGroupName: skin.skinGroupName || translatedGroup || rawGroupName,
    };
  }

  if (translatedGroup) {
    return {
      skinGroupName: translatedGroup,
    };
  }

  return undefined;
}

/**
 * Looks up module localization
 */
export function getModuleLocalizationRu(
  charId: string,
  moduleId: string
): RuModuleLocalization | undefined {
  return RU_OPERATORS_DB[charId]?.modules?.[moduleId];
}
