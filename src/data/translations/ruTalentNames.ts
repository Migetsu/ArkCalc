/**
 * Translates talent name into Russian with fallback to glossary and cleaning
 */
export function translateTalentNameRu(rawName: string): string {
  if (!rawName) return '';
  const trimmed = rawName.trim();
  if (RU_TALENT_NAMES[trimmed]) {
    return RU_TALENT_NAMES[trimmed];
  }
  if (CN_TALENT_NAMES_MAP[trimmed]) {
    return CN_TALENT_NAMES_MAP[trimmed].ru;
  }
  return trimmed;
}
